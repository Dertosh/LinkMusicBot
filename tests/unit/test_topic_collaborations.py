import unittest
from unittest.mock import patch
from linkmusicbot.services import YouTube
from linkmusicbot.services.base import same_recording
from linkmusicbot.models import Song
from linkmusicbot.search_ranking import rank_results


class TopicCollaborationTests(unittest.TestCase):
    def test_search_enriches_topic_credits_before_merging_platforms(self):
        title='#ЛЯШКИВКУСНЯШКИ ([prod.by Kolji])'
        search={'items':[{'id':{'videoId':'Q8EKt6NUCSE'},'snippet':{'title':title,'channelTitle':'ЯКОРЪ - Topic'}}]}
        snippet={'title':title,'channelTitle':'ЯКОРЪ - Topic','description':'Provided to YouTube by Label\n\n'+title+' · ЯКОРЪ · НАВЕРНОЕ ПОЭТ\n\nAuto-generated by YouTube.'}
        with patch.object(YouTube,'_get',side_effect=[search,{'items':[{'id':'Q8EKt6NUCSE','snippet':snippet}]}]):
            result=list(YouTube().search('ляшки'))[0]
        self.assertEqual(result.artist,'ЯКОРЪ & НАВЕРНОЕ ПОЭТ')
        self.assertTrue(same_recording(result,'#ЛЯШКИВКУСНЯШКИ - [prod.by Kolji]','ЯКОРЪ & НАВЕРНОЕ ПОЭТ'))
        self.assertFalse(same_recording(result,'#ЛЯШКИВКУСНЯШКИ (EDIT VERSION) - prod.by Kolji','ЯКОРЪ & НАВЕРНОЕ ПОЭТ'))

    def test_original_precedes_edit_version(self):
        original=Song('#ЛЯШКИВКУСНЯШКИ (prod.by Kolji)','ЯКОРЪ & НАВЕРНОЕ ПОЭТ','')
        edited=Song('#ЛЯШКИВКУСНЯШКИ (EDIT VERSION) [prod.by Kolji]','ЯКОРЪ & НАВЕРНОЕ ПОЭТ','')
        self.assertIs(rank_results([edited,original],'ляшкивкусняшки')[0],original)
        edited.title='#ЛЯШКИВКУСНЯШКИ (EDIT VERSION) - prod.by Kolji'
        self.assertIs(rank_results([edited,original],'ляшкивкусняшки')[0],original)
